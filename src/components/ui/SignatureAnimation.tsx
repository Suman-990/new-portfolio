export const SignatureAnimation: React.FC<SignatureAnimationProps> = ({
  className = "",
  strokeWidth = 4.5,
  strokeColor,
  variant = "suman",
  speedMultiplier = 1.65,
}) => {
  const svgRef = useRef<SVGSVGElement>(null)
  const raf1Ref = useRef<number | null>(null)
  const raf2Ref = useRef<number | null>(null)

  const signatureData = variant === "suman" ? SUMAN_SIGNATURE : CODEPEN_SIGNATURE

  const cancelPendingFrames = useCallback(() => {
    if (raf1Ref.current !== null) {
      cancelAnimationFrame(raf1Ref.current)
      raf1Ref.current = null
    }
    if (raf2Ref.current !== null) {
      cancelAnimationFrame(raf2Ref.current)
      raf2Ref.current = null
    }
  }, [])

  /**
   * Precise stroke-by-stroke animation algorithm matching the user's CodePen reference:
   * 1. Measures each path's total length via DOM getTotalLength()
   * 2. Sets strokeDasharray and strokeDashoffset to length
   * 3. Calculates dynamic speed and sequential delay
   * 4. Transitions strokeDashoffset to 0 sequentially at a natural handwriting pace
   */
  const animate = useCallback(() => {
    if (!svgRef.current) return
    cancelPendingFrames()

    const paths = Array.from(
      svgRef.current.querySelectorAll<SVGGeometryElement>("path, circle, rect")
    )
    if (paths.length === 0) return

    // 1. Reset all paths immediately
    let delay = 0
    let previousSpeed = 0
    const pauseBetweenStrokes = 65

    paths.forEach((path, index) => {
      const length = path.getTotalLength()
      // Scaled for a smooth, relaxed handwriting pace
      const isCrossbar = index === paths.length - 1
      const minSpeed = isCrossbar ? 170 : 80
      const speed = Math.max(minSpeed, Math.floor(length * speedMultiplier))

      // Natural pen-lift delay between strokes; slightly longer before crossing the 't'
      const penLiftPause = isCrossbar ? 150 : pauseBetweenStrokes
      delay += previousSpeed + penLiftPause
      previousSpeed = speed

      path.style.transition = "none"
      path.style.strokeDasharray = `${length} ${length}`
      path.style.strokeDashoffset = `${length}`

      path.setAttribute("data-speed", speed.toString())
      path.setAttribute("data-delay", delay.toString())
    })

    // Force browser style recalculation/reflow before applying transitions
    // eslint-disable-next-line @typescript-eslint/no-unused-expressions
    svgRef.current.getBoundingClientRect()

    // 2. Animate paths sequentially in double RAF
    raf1Ref.current = requestAnimationFrame(() => {
      raf2Ref.current = requestAnimationFrame(() => {
        paths.forEach((path) => {
          const speed = path.getAttribute("data-speed") || "300"
          const delayMs = path.getAttribute("data-delay") || "0"
          path.style.transition = `stroke-dashoffset ${speed}ms cubic-bezier(0.35, 0.1, 0.25, 1) ${delayMs}ms`
          path.style.strokeDashoffset = "0"
        })
      })
    })
  }, [speedMultiplier, cancelPendingFrames])

  // Trigger animation on initial mount and whenever variant changes
  useEffect(() => {
    const timer = setTimeout(() => {
      animate()
    }, 350)
    return () => {
      clearTimeout(timer)
      cancelPendingFrames()
    }
  }, [animate, cancelPendingFrames])

  return (
    <div
      className={`relative flex flex-col items-center justify-center ${className}`}
    >
      {/* Outer container: replays drawing animation every time on hover */}
      <div
        className="relative w-full max-w-[340px] sm:max-w-[380px] md:max-w-[400px] cursor-pointer select-none transition-transform duration-300 hover:scale-[1.02] active:scale-[0.98]"
        onMouseEnter={() => animate()}
        onClick={() => animate()}
        role="button"
        tabIndex={0}
        onKeyDown={(e) => {
          if (e.key === "Enter" || e.key === " ") {
            e.preventDefault()
            animate()
          }
        }}
      >
        {/* Signature SVG container */}
        <div className="relative w-full overflow-visible py-1">
          <svg
            ref={svgRef}
            xmlns="http://www.w3.org/2000/svg"
            viewBox={signatureData.viewBox}
            className="w-full h-auto drop-shadow-[0_2px_4px_rgba(0,0,0,0.06)]"
            preserveAspectRatio="xMidYMid meet"
          >
            {signatureData.paths.map((d, index) => (
              <path
                key={`${variant}-${index}`}
                fill="none"
                stroke={strokeColor || "var(--color-ink, #14130f)"}
                strokeWidth={strokeWidth}
                strokeLinecap="round"
                strokeLinejoin="round"
                d={d}
                style={{
                  strokeMiterlimit: 10,
                  opacity: 0.92,
                }}
              />
            ))}
          </svg>
        </div>
      </div>
    </div>
  )
}

export default SignatureAnimation
